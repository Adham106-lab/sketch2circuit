/**
 * Converts a text string into scaled, translated, rotated 2D line segments.
 */
export function renderTextToStrokes(
  text: string,
  startX: number,
  startY: number,
  fontSizeMm: number,
  rotationDeg = 0,
): StrokeSegment[] {
  const result: StrokeSegment[] = [];
  const charWidth = fontSizeMm * 0.7;
  const charSpacing = fontSizeMm * 0.85;
  const rad = (rotationDeg * Math.PI) / 180;
  const cos = Math.cos(rad);
  const sin = Math.sin(rad);

  for (let i = 0; i < text.length; i++) {
    const rawChar = text[i] ?? " ";
    const ch = rawChar.toUpperCase();
    const glyph = FONT_GLYPHS[ch] || FONT_GLYPHS[" "] || [];
    const charOffsetX = i * charSpacing;

    for (const [gx1, gy1, gx2, gy2] of glyph) {
      // Local coordinate in text space
      const lx1 = charOffsetX + gx1 * charWidth;
      const ly1 = gy1 * fontSizeMm;
      const lx2 = charOffsetX + gx2 * charWidth;
      const ly2 = gy2 * fontSizeMm;

      // Rotate and translate to world board space
      const wx1 = startX + (lx1 * cos - ly1 * sin);
      const wy1 = startY + (lx1 * sin + ly1 * cos);
      const wx2 = startX + (lx2 * cos - ly2 * sin);
      const wy2 = startY + (lx2 * sin + ly2 * cos);

      result.push({ x1: wx1, y1: wy1, x2: wx2, y2: wy2 });
    }
  }

  return result;
}
